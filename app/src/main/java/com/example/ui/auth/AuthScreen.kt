                        verticalArrangement = Arrangement.spacedBy(14.dp)
                    ) {
                        FeatureRow(
                            icon = Icons.Rounded.AutoGraph,
                            title = "Automatic Udhar-Jama Hisab",
                            subtitle = "Real-time customer balances & running ledger"
